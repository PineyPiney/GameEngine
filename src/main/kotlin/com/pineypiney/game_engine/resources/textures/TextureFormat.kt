		RGB_INT(GL_RED_INTEGER, 3),
		RGBA(GL_RED, 4),
		RGBA_INT(GL_RED_INTEGER, 4),
		DEPTH(GL_DEPTH_COMPONENT, 1),
		DEPTH_STENCIL(GL_DEPTH_STENCIL, 2),
	}
