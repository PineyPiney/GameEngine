	companion object {
		fun fromGlConst(value: Int): TextureFormat? {
			return TextureFormat.entries.firstOrNull { it.opengl == value }
		}

		fun fromVulkanConst(value: Int): TextureFormat? {
			return TextureFormat.entries.firstOrNull { it.vulkan == value }
		}
	}

