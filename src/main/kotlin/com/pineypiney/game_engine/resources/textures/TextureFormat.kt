	var supported = true

	fun getAspects(): List<TextureAspect>{
		return when(openglLayout){
			GL_DEPTH_STENCIL -> listOf(TextureAspect.DEPTH, TextureAspect.STENCIL)
			GL_DEPTH_COMPONENT -> listOf(TextureAspect.DEPTH)
			GL_STENCIL_INDEX -> listOf(TextureAspect.STENCIL)
			else -> listOf(TextureAspect.COLOUR)
		}
	}

	companion object {
		fun fromGlConst(value: Int): TextureFormat? {
			GL_DEPTH32F_STENCIL8
			return TextureFormat.entries.firstOrNull { it.opengl == value }
		}

		fun fromVulkanConst(value: Int): TextureFormat? {
			return TextureFormat.entries.firstOrNull { it.vulkan == value }
		}
	}

	enum class Channels(val id: Int, val size: Int){
		R(GL_RED, 1),
		R_INT(GL_RED_INTEGER, 1),
		RG(GL_RED, 2),
		RG_INT(GL_RED_INTEGER, 2),
