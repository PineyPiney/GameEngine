package com.pineypiney.game_engine.resources.textures

import org.lwjgl.opengl.GL46C.*

enum class ChannelFormat(val opengl: Int, val bytes: Int) {
	BYTE(GL_BYTE, 1),
	UBYTE(GL_UNSIGNED_BYTE, 1),
	SNORM8(GL_BYTE, 1),
	UNORM8(GL_UNSIGNED_BYTE, 1),
	SRGB8(GL_UNSIGNED_BYTE, 1),

	SHORT(GL_SHORT, 2),
	USHORT(GL_UNSIGNED_SHORT, 2),
	SNORM16(GL_SHORT, 2),
	UNORM16(GL_UNSIGNED_SHORT, 2),

	INT(GL_INT, 4),
	UINT(GL_UNSIGNED_INT, 4),

	H_FLOAT(GL_HALF_FLOAT, 2),
	FLOAT(GL_FLOAT, 4),

	UNORM565(GL_UNSIGNED_SHORT_5_6_5, 2),
	UNORM4444(GL_UNSIGNED_SHORT_4_4_4_4, 2),
	UNORM5551(GL_UNSIGNED_SHORT_5_5_5_1, 2),
	UNORM1010102(GL_UNSIGNED_INT_10_10_10_2, 4),
	UINT1010102(GL_UNSIGNED_INT_10_10_10_2, 4),

	// Depth-Stencil Formats
	UNORM24UINT8(GL_UNSIGNED_INT_24_8, 4),
	FLOAT32UINT8(GL_FLOAT_32_UNSIGNED_INT_24_8_REV, 8),

	FLOAT111110(-1, 4),
}