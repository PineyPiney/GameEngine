package com.pineypiney.game_engine.window

import org.lwjgl.glfw.GLFW
import org.lwjgl.sdl.SDLVideo

enum class WindowFlags(override val glfw: Int, override val sdl: Long) : WindowEnum<Long> {
	FOCUSED(GLFW.GLFW_FOCUSED, SDLVideo.SDL_WINDOW_INPUT_FOCUS),
	RESIZABLE(GLFW.GLFW_RESIZABLE, SDLVideo.SDL_WINDOW_RESIZABLE),
	MINIMISED(GLFW.GLFW_ICONIFIED, SDLVideo.SDL_WINDOW_MINIMIZED),
	MAXIMISED(GLFW.GLFW_MAXIMIZED, SDLVideo.SDL_WINDOW_MAXIMIZED),
	FLOATING(GLFW.GLFW_FLOATING, SDLVideo.SDL_WINDOW_ALWAYS_ON_TOP),
	TRANSPARENT(GLFW.GLFW_TRANSPARENT_FRAMEBUFFER, SDLVideo.SDL_WINDOW_TRANSPARENT),
}